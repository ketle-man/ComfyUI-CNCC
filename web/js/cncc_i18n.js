function currentLang() {
    let locale = "en";
    try {
        locale = app.extensionManager?.setting?.get?.("Comfy.Locale") || "en";
    } catch (err) {
        locale = "en";
    }
    const short = String(locale).split("-")[0].toLowerCase();
    return DICT[short] ? short : "en";
}

export function t(key, params) {
    const dict = DICT[currentLang()] || DICT.en;
    let str = dict[key] ?? DICT.en[key] ?? key;
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            str = str.replace(`{${k}}`, v);
        }
    }
    return str;
}
